"""Parallel, resumable qualification of every source frame; no temporal sampling.

Uses calibration already generated by clean-realsense-scene.py. Each frame has
an atomic provenance sidecar, so interrupted work can be resumed without guesses.
"""
import argparse
from collections import Counter
from concurrent.futures import ThreadPoolExecutor
import hashlib
import importlib.util
import json
from pathlib import Path
import sqlite3
import threading
import time

import cv2
import numpy as np
from PIL import Image, ImageDraw
from threadpoolctl import threadpool_limits

spec=importlib.util.spec_from_file_location('clean',Path(__file__).with_name('clean-realsense-scene.py'))
clean=importlib.util.module_from_spec(spec);spec.loader.exec_module(clean)


def main():
    ap=argparse.ArgumentParser(description=__doc__)
    ap.add_argument('--root',type=Path,default=Path('data/realsense_20261030_111354_all30'))
    ap.add_argument('--recording',type=Path,default=Path('20261030_111354.db3'))
    ap.add_argument('--workers',type=int,default=4)
    a=ap.parse_args();root=a.root.resolve();source=a.recording.resolve();before=source.stat()
    parameters=dict(fps=30.,width=848,min_sharpness=25.,max_delta=.02,near=.3,far=6.,all_frames=True)
    if (root/'capture_manifest.json').exists():
        m=clean.check_source(root)
        if m['parameters']!=parameters:
            raise ValueError('Existing extraction settings differ')
        print('ALL_FRAME_EXTRACTION already complete',flush=True);return
    cal=json.loads((root/'calibration_clean.json').read_text());c,d=cal['raw_color'],cal['raw_depth']
    K=np.array(cal['K']);rawK=clean.intrinsic(c);R=np.array(cal['depth_to_color_R']);t=np.array(cal['depth_to_color_t_m'])
    width,height=cal['width'],cal['height'];yy,xx=np.mgrid[:height,:width]
    ideal=np.column_stack(((xx.ravel()-K[0,2])/K[0,0],(yy.ravel()-K[1,2])/K[1,1]))
    coeff=np.array([float(v) for v in c['coeffs'].split(',')])
    raw=clean.invert_brown(ideal,coeff) if c['model']=='Inverse Brown Conrady' else clean.brown(ideal,coeff)
    maps=(raw*[rawK[0,0],rawK[1,1]]+[rawK[0,2],rawK[1,2]]).reshape(height,width,2).astype('f4')
    for name in ('frame_metadata','images','aligned_depth_meters','imu'):
        (root/name).mkdir(exist_ok=True)
    uri=source.as_uri()+'?mode=ro'
    with sqlite3.connect(uri,uri=True) as db:
        db.execute('PRAGMA query_only=ON')
        if db.execute('PRAGMA quick_check').fetchall()!=[('ok',)]:
            raise ValueError('SQLite integrity failed')
        topics=db.execute('select id,name,type from topics').fetchall()
        def tid(suffix):return next(i for i,n,typ in topics if n.endswith(suffix))
        rgbrows=db.execute('select id,timestamp from messages where topic_id=? order by timestamp',(tid('/Color_0/image/data'),)).fetchall()
        drows=db.execute('select id,timestamp from messages where topic_id=? order by timestamp',(tid('/Depth_0/image/data'),)).fetchall()
        stamps=np.array([stamp for _,stamp in drows],dtype=np.int64)
        if not np.all(np.diff(stamps)>0):raise ValueError('Depth timestamps not strictly increasing')
        topic_report=[dict(name=n,type=typ,count=db.execute('select count(*) from messages where topic_id=?',(i,)).fetchone()[0]) for i,n,typ in topics]
        imu=clean.imu_export(db,topics,root/'imu')
    fingerprint=hashlib.sha256(json.dumps(dict(source=str(source),bytes=before.st_size,mtime=before.st_mtime_ns,cal=cal,parameters=parameters),sort_keys=True).encode()).hexdigest()
    local=threading.local()
    def process(item):
        index,(mid,stamp)=item;name=f'frame_{index:06d}.png';sidecar=root/'frame_metadata'/(name+'.json')
        if sidecar.exists():
            saved=json.loads(sidecar.read_text())
            if saved['fingerprint']!=fingerprint or saved['record']['message_id']!=mid:
                raise ValueError('Resume metadata differs from current source/settings')
            if not saved['accepted'] or ((root/'images'/name).exists() and (root/'aligned_depth_meters'/(name+'.npz')).exists()):
                return saved
        if not hasattr(local,'db'):
            local.db=sqlite3.connect(uri,uri=True)
            local.db.execute('PRAGMA query_only=ON')
        db=local.db
        blob=db.execute('select data from messages where id=?',(mid,)).fetchone()[0]
        rgb,h=clean.capture.CDR(blob).image();q=clean.rgb_quality(rgb)
        rec=dict(message_id=mid,timestamp_ns=stamp,**h,**q)
        reasons=clean.rejection(q,25.)
        j=int(np.searchsorted(stamps,stamp));j=min([max(0,j-1),min(len(stamps)-1,j)],key=lambda k:abs(int(stamps[k])-stamp))
        dt=abs(int(stamps[j])-stamp)/1e9
        if dt>.02:reasons.append('timestamp_pair_gap')
        if not reasons:
            dep,dh=clean.adapter.decode_depth(db.execute('select data from messages where id=?',(drows[j][0],)).fetchone()[0])
            hd=abs(dh-rec['header_seconds'])
            if hd>.02:reasons.append('header_pair_gap')
        if not reasons:
            p,z,fraction=clean.clean_depth(dep,cal['depth_units'],d,R,t,K,width,height)
            if len(z)<1500:reasons.append('insufficient_valid_depth')
        if reasons:
            saved=dict(fingerprint=fingerprint,accepted=False,record=dict(**rec,reasons=reasons))
        else:
            im=cv2.remap(rgb,maps[:,:,0],maps[:,:,1],cv2.INTER_LINEAR)
            Image.fromarray(im).save(root/'images'/name,compress_level=1)
            keep=np.random.default_rng(mid).choice(len(z),min(16000,len(z)),replace=False)
            np.savez_compressed(root/'aligned_depth_meters'/(name+'.npz'),points=p[keep],depths=z[keep])
            saved=dict(fingerprint=fingerprint,accepted=True,record=dict(**rec,name=name,depth_message_id=drows[j][0],
                       depth_timestamp_ns=int(stamps[j]),depth_header_seconds=dh,pair_delta_seconds=dt,header_delta_seconds=hd,
                       depth_valid_fraction=fraction,aligned_samples=len(z),previous_mean_abs_difference=None))
        clean.write(sidecar,saved);return saved
    cv2.setNumThreads(1);frames=[];rejected=[]
    started=time.time()
    with threadpool_limits(limits=1),ThreadPoolExecutor(max_workers=a.workers) as executor:
        for j,result in enumerate(executor.map(process,enumerate(rgbrows))):
            (frames if result['accepted'] else rejected).append(result['record'])
            if j%100==0:
                print('ALL30',j+1,'/',len(rgbrows),'accepted',len(frames),'rejected',len(rejected),'elapsed',round(time.time()-started,1),flush=True)
                clean.write(root/'pipeline_status.json',dict(stage='clean_all_frames',status='running',processed=j+1,total=len(rgbrows),accepted=len(frames),rejected=len(rejected)))
    after=source.stat()
    if (after.st_size,after.st_mtime_ns)!=(before.st_size,before.st_mtime_ns):raise ValueError('Source recording changed')
    if len(frames)+len(rejected)!=len(rgbrows):raise ValueError('Unaccounted source frames')
    clean.write(root/'rejected_frames.json',rejected);clean.write(root/'imu/report.json',imu)
    clean.write(root/'capture_manifest.json',dict(source=str(source),source_bytes=before.st_size,source_mtime_ns=before.st_mtime_ns,
                source_open_mode='read-only',sqlite_quick_check='ok',parameters=parameters,raw_rgb_frames=len(rgbrows),raw_depth_frames=len(drows),
                duration_seconds=(rgbrows[-1][1]-rgbrows[0][1])/1e9,topics=topic_report,frames=frames))
    clean.write(root/'cleaning_report.json',dict(raw_rgb_frames=len(rgbrows),accepted_frames=len(frames),rejected_frames=len(rejected),
         all_source_frames_accounted=True,selection_mode='Every recorded RGB frame; no temporal sampling, binning or near-duplicate removal',
         rejection_reasons=dict(Counter(reason for f in rejected for reason in f['reasons'])),parameters=parameters,
         pair_delta_seconds_percentiles=np.percentile([f['pair_delta_seconds'] for f in frames],[0,50,95,100]).tolist(),
         sharpness_percentiles=np.percentile([f['sharpness'] for f in frames],[0,50,100]).tolist(),
         depth_valid_fraction_percentiles=np.percentile([f['depth_valid_fraction'] for f in frames],[0,50,100]).tolist(),
         workers=a.workers,elapsed_seconds=time.time()-started,raw_rgb_policy='No exposure equalization; geometric resampling only'))
    sheet=Image.new('RGB',(1280,800),'#222222');draw=ImageDraw.Draw(sheet)
    for j,i in enumerate(np.linspace(0,len(frames)-1,16,dtype=int)):
        f=frames[i];im=Image.open(root/'images'/f['name']);im.thumbnail((320,175));x,y=j%4*320,j//4*200
        sheet.paste(im,(x,y+25));draw.text((x+3,y+3),f['name']+' | '+str(round(f['timestamp_ns']/1e9,2))+'s',fill='white')
    sheet.save(root/'clean_preview.jpg')
    clean.write(root/'pipeline_status.json',dict(stage='clean_all_frames',status='complete',accepted=len(frames),rejected=len(rejected)))
    print('ALL30_CLEAN_COMPLETE',len(frames),len(rejected),flush=True)


if __name__=='__main__':main()
